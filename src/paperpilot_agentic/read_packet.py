"""A question-scoped, whole-source window shared by generation and review.

Selection is navigation, never a factual verdict. Omitted originals remain owned
by the caller and reloadable through the existing bounded recovery path.
"""
from dataclasses import dataclass
import json
import re
from .structured_extraction import config_sha

VERSION = 'shared-read-packet-v6-object-anchors'
NAVIGATION_QUERY = re.compile(r'参考文献|作者(?:信息|简介)|bibliograph|references|author biographies', re.I)
BACK_MATTER = re.compile(r'^\s*(?:REFERENCES|BIBLIOGRAPHY|AUTHOR BIOGRAPH(?:IES)?|参考文献)\s*$', re.I | re.M)
QUERY_STOPWORDS = frozenset('a an the and or of to in on for with from by is are was were be '
    'this that these those it its what which how why who please describe explain give show compare'.split())


class SourceCoverageError(ValueError):
    """Evidence coverage failed; spending more is not a remedy by itself."""


def exact_page(row):
    provenance = row.get('provenance') or {}
    if provenance.get('page_precision') in {'RANGE', 'UNKNOWN'}:
        return None
    page = row.get('page')
    return page if type(page) is int and page > 0 else None


@dataclass(frozen=True)
class ReadPacket:
    rows: list[dict]
    identity: str
    metadata: dict
    question: str
    requested_tables: list[dict] | None


def validate_shared_packet(packet, question, evidence, max_bytes):
    """Verify a host-selected packet without selecting its contents again."""
    if (not isinstance(packet, ReadPacket) or packet.question != question or
            packet.rows != evidence or packet.metadata.get('policy') != VERSION or
            packet.metadata.get('context_upper_bytes', max_bytes + 1) > max_bytes or
            packet.identity != config_sha({'version': VERSION, 'question': packet.question,
                'rows': packet.rows, 'requested_tables': packet.requested_tables,
                'metadata': packet.metadata})):
        raise ValueError('Shared read packet identity or source contents changed')
    return packet


def operation_definition_priority(question, text):
    """A bounded navigation preference, never a factual correctness verdict."""
    query = re.sub(r'《[^《》]+》', ' ', question)
    terms = set(re.findall(r'[a-z][a-z0-9_-]{1,}', query.lower())) - QUERY_STOPWORDS
    hits = sum(bool(re.search(
        r'(?<![a-z0-9_])' + re.escape(term) +
        r'(?:\s+[a-z-]+){0,3}\s+(?:is|are|means|uses|works|performs|consists)\b',
        text, re.I)) for term in terms)
    operations = bool(re.search(r'unfold\w*|cross-order\w*|concatenat\w*|warping|'
                               r'channel dimension|temporal order|交替|拼接|展开|通道维', text, re.I))
    procedural = bool(re.search(r'we (?:propose|introduce)|first processed|fed into|'
                                r'generated by|consists of|首先|输入到|生成', text, re.I))
    named = any(re.search(r'(?<![a-z0-9_])' + re.escape(term) + r'(?![a-z0-9_])',
                         text, re.I) for term in terms)
    generic = 0
    if not terms and re.search(r'机制|原理|组织|\bmechanism\b', query, re.I):
        # A Chinese follow-up need not repeat English method names. Prefer
        # actual operation definitions over abstracts that only announce them.
        normalized = re.sub(r'\s+', ' ', text)
        definitions = len(re.findall(r'\bmodeling is\b|\bby (?:concatenating|cross.ordering|unfolding)\b|'
                                     r'\bgenerated by aligning\b', normalized, re.I))
        generic = int(procedural) + min(3, definitions)
    return 150 * max(hits + int(procedural and named), generic) if operations else 0


def purpose_definition_priority(question, text):
    """Keep stated problem/goal passages eligible when the user asks why.

    A lexical navigation hint only: neither goal wording nor matching a method
    name establishes actor ownership or factual support; the audit still does.
    """
    query = re.sub(r'《[^《》]+》', ' ', question)
    if not re.search(r'解决|目的|目标|为何|为什么|处理|针对|\b(?:purpose|problem|aim|motivation)\b', query, re.I):
        return 0
    # Capitalized method identifiers/acronyms are more specific than generic
    # query words such as token/problem. Do not match Cross to cross-attention.
    identifiers = {term for term in re.findall(r'\b[A-Z][A-Za-z0-9_-]+\b', query)
                   if term.lower() not in QUERY_STOPWORDS | {'table'}}
    named = not identifiers or any(re.search(r'(?<![A-Za-z0-9_-])'+re.escape(term)+r'(?![A-Za-z0-9_-])', text)
                                   for term in identifiers)
    normalized = re.sub(r'\s+', ' ', text)
    problem = re.search(r'\bto (?:address|mitigate|overcome|alleviate)\b|为了解决', normalized, re.I)
    goal = re.search(r'\b(?:aims?|designed|intended) to\b|旨在|目的是', normalized, re.I)
    return (600 if problem else 300 if goal else 0) if named else 0


def build_read_packet(question, candidates, *, max_bytes=24000, requested_tables=None):
    if type(max_bytes) is not int or max_bytes < 0:
        raise ValueError('Invalid read packet byte limit')
    wants_back = bool(NAVIGATION_QUERY.search(question))
    from .numeric_scope import metric_references
    wants_tables = bool(requested_tables or metric_references(question) or re.search(r'表\s*(?:[IVXLCDM\d]+)|\btable\b|消融|ablation|数值|指标|结果|score|result', question, re.I))
    content_question = re.sub(r'《[^《》]+》', ' ', question)
    terms = set(re.findall(r'[a-z][a-z0-9_-]{1,}', content_question.lower())) - QUERY_STOPWORDS
    def matches(term, text):
        return bool(re.search(r'(?<![a-z0-9_])' + re.escape(term) + r'(?![a-z0-9_])', text.lower()))
    frequencies = {term: sum(matches(term, r['content']) for r in candidates) for term in terms}
    # Paper titles repeat on every indexed chunk. They identify scope, not a
    # reason to send every abstract, reference and unrelated experiment.
    specific_terms = {term for term in terms if 0 < frequencies[term] < max(2, len(candidates) * .8)}
    terms = specific_terms or terms
    required = {(r['paper_sha256'], r['label'].lower()) for r in requested_tables or []}
    back_pages = {}
    for row in candidates:
        if BACK_MATTER.search(row['content']) and exact_page(row) is not None:
            uri = str(row.get('source_uri') or '')
            paper = uri.split('/')[2] if uri.startswith('paper://') else uri
            back_pages[paper] = min(back_pages.get(paper, row['page']), row['page'])
    ranked, omitted = [], []
    definition_priorities = {}
    for index, row in enumerate(candidates):
        provenance = row.get('provenance') or {}
        text = row['content']
        section = ' '.join(map(str, provenance.get('section_path') or []))
        role = str(provenance.get('section_role') or provenance.get('role') or '')
        is_back = bool(BACK_MATTER.search(text) or re.search(r'references|bibliography|biography|author_info', section + ' ' + role, re.I))
        # Bibliography entries and biographies are often split away from their
        # heading by the PDF index. Require recognizable entry/biography shape.
        is_back |= bool(re.match(r'\s*\[\d+\]\s+[A-Z].{3,}', text) and re.search(r'\b(?:vol\.|pp\.|doi|IEEE|arXiv|Proceedings)\b', text))
        is_back |= bool(re.search(r'\b(?:received the (?:B\.|M\.|Ph\.)|is currently (?:a|an) (?:Ph|professor)|research interests include)\b', text, re.I))
        typed = provenance.get('structured_extraction') or {}
        table = (typed.get('kind') == 'table' or row.get('object_type') == 'table'
                 or bool(re.match(r'^\s*TABLE\s+(?:[IVXLCDM]+|\d+)(?:[.\s]|$)', text, re.I)))
        source = typed.get('source') or {}
        uri = str(row.get('source_uri') or '')
        paper = source.get('paper_sha256') or (uri.split('/')[2] if uri.startswith('paper://') else uri)
        demanded = (paper, str(source.get('label', '')).lower()) in required
        is_back |= (not table and exact_page(row) is not None and paper in back_pages
                    and row['page'] >= back_pages[paper])
        if (is_back and not wants_back) or (table and not wants_tables):
            omitted.append({'evidence_id': row['evidence_id'], 'source_uri': uri,
                            'page': row.get('page'), 'reason': 'outside_current_scope'})
            continue
        hits = sum(1 / max(1, frequencies[term]) for term in terms if matches(term, text))
        method = bool(re.search(r'method|architecture|proposed|metric|implementation|experiment', section + ' ' + role, re.I))
        definition_priority = operation_definition_priority(question, text)
        definition_priorities[row['evidence_id']] = definition_priority
        purpose_priority = purpose_definition_priority(question, text)
        anchored = bool(provenance.get('navigation_anchor', {}).get('question') == question)
        if specific_terms and hits == 0 and not method and not definition_priority and not purpose_priority and not demanded and not table and not anchored:
            omitted.append({'evidence_id': row['evidence_id'], 'source_uri': uri,
                            'page': row.get('page'), 'reason': 'no_question_content_match'})
            continue
        ranked.append((1000 if demanded or anchored else 100 if table and wants_tables else
                       100 * hits + 15 * method + definition_priority + purpose_priority,
                       index, paper, row))
    strongest = {}
    for priority, _, paper, _ in ranked:
        if priority < 1000:
            strongest[paper] = max(strongest.get(paper, 0), priority)
    eligible = []
    for item in ranked:
        priority, _, paper, row = item
        if priority < 100 and priority < strongest.get(paper, 0) * .35:
            omitted.append({'evidence_id': row['evidence_id'], 'source_uri': row.get('source_uri'),
                            'page': row.get('page'), 'reason': 'lower_question_relevance_navigation_only'})
        else:
            eligible.append(item)
    ranked = eligible
    # Preserve retrieval rank on ties; alternate papers at each priority tier
    # rather than allowing one long section to starve the other paper.
    ranked.sort(key=lambda r: (-r[0], r[1]))
    ordered, seen = [], set()
    while ranked:
        remaining = []
        for item in ranked:
            if item[2] not in seen:
                ordered.append(item)
                seen.add(item[2])
            else:
                remaining.append(item)
        ranked, seen = remaining, set()
    # Protect one strongest operation definition per paper before filling the
    # remaining window with purpose/context passages. A high-scoring abstract
    # must not displace the operations required by a mechanism comparison.
    anchors = {}
    if re.search(r'机制|原理|组织|\b(?:mechanisms?|architecture)\b', question, re.I):
        for item in ordered:
            score = definition_priorities[item[3]['evidence_id']]
            if score and (item[2] not in anchors or
                          (score, -item[1]) > (definition_priorities[anchors[item[2]][3]['evidence_id']], -anchors[item[2]][1])):
                anchors[item[2]] = item
    anchor_ids = {item[3]['evidence_id'] for item in anchors.values()}
    ordered = ([item for item in ordered if item[0] == 1000] +
               [item for item in ordered if item[0] != 1000 and item[3]['evidence_id'] in anchor_ids] +
               [item for item in ordered if item[0] != 1000 and item[3]['evidence_id'] not in anchor_ids])
    selected, used = [], 2
    for priority, _, paper, row in ordered:
        view = {key: row.get(key) for key in ('evidence_id', 'source_uri', 'page', 'content')}
        size = len(json.dumps(view, ensure_ascii=False).encode()) + 2
        if used + size <= max_bytes:
            selected.append(row)
            used += size
        else:
            omitted.append({'evidence_id': row['evidence_id'], 'source_uri': view['source_uri'],
                            'page': view['page'], 'reason': 'whole_source_does_not_fit', 'required': priority == 1000})
    papers = {str(r.get('source_uri') or '').split('/')[2] for r in candidates
              if str(r.get('source_uri') or '').startswith('paper://')}
    represented = {str(r.get('source_uri') or '').split('/')[2] for r in selected
                   if str(r.get('source_uri') or '').startswith('paper://')}
    metadata = {'policy': VERSION, 'candidate_count': len(candidates), 'selected_count': len(selected),
        'selected_evidence_ids': [r['evidence_id'] for r in selected],
        'omitted_evidence_ids': [r['evidence_id'] for r in omitted], 'unread_navigation_only': omitted,
        'unrepresented_sources': sorted(papers - represented), 'context_upper_bytes': used,
        'max_bytes': max_bytes, 'summarized': False, 'semantic_coverage': 'NOT_PROVEN',
        'operation_definition_anchors': sorted(anchor_ids),
        'required_source_gaps': [r for r in omitted if r.get('required')]}
    identity = config_sha({'version': VERSION, 'question': question, 'rows': selected,
                           'requested_tables': requested_tables, 'metadata': metadata})
    return ReadPacket(selected, identity, metadata, question, requested_tables)
